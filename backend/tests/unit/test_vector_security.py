@pytest.mark.asyncio
async def test_retrieve_node_state_rbac_credentials():
    """Test LangGraph retrieve_node extracts user RBAC credentials and applies security filtering."""
    query = "研发部主管可以审批多少额度的设备采购？"

    # State with low clearance user
    state_cs: AgentState = {
        "messages": [HumanMessage(content=query)],
        "current_step": "init",
        "context": [],
        "user_id": "cs_user_01",
        "metadata": {
            "user": {
                "tenant_id": "default",
                "department": "客服部",
                "clearance_level": 1,
            }
        },
    }

    res_cs = await retrieve_node(state_cs)
    assert res_cs["current_step"] == "retrieved"
    assert "context" in res_cs

    # State with finance manager
    state_fin: AgentState = {
        "messages": [HumanMessage(content=query)],
        "current_step": "init",
        "context": [],
        "user_id": "fin_director_01",
        "metadata": {
            "user": {
                "tenant_id": "default",
                "department": "财务部",
                "clearance_level": 3,
            }
        },
    }

    res_fin = await retrieve_node(state_fin)
    assert res_fin["current_step"] == "retrieved"
    assert len(res_fin["context"]) >= 1
