def test_document_security_model_and_defaults():
    """Test DocumentSecurity model validation and default security level injection."""
    sec = DocumentSecurity(
        tenant_id="tenant_001",
        allowed_departments=["研发部", "财务部"],
        security_clearance_level=3,
    )
    assert sec.tenant_id == "tenant_001"
    assert "研发部" in sec.allowed_departments
    assert sec.security_clearance_level == 3

    # Default fallback
    default_sec = DocumentSecurity()
    assert default_sec.tenant_id == "default"
    assert default_sec.allowed_departments == ["ALL"]
    assert default_sec.security_clearance_level == 1


def test_build_rbac_filter_structure():
    """Test Qdrant Filter structure generated by build_rbac_filter."""
    q_filter = build_rbac_filter(
        tenant_id="enterprise_alpha",
        user_department="市场部",
        clearance_level=2,
    )
    must_conditions = q_filter.must
    assert len(must_conditions) == 3

    keys = [c.key for c in must_conditions]
    assert "tenant_id" in keys
    assert "allowed_departments" in keys
    assert "security_clearance_level" in keys


def test_rbac_security_isolation_in_qdrant():
    """Test standard employee (clearance=1) vs finance/executive (clearance=3) retrieval in Qdrant."""
    test_client = QdrantClient(":memory:")
    collection_name = "test_security_kb"

    # Prepare sensitive finance and public docs
    docs = [
        Document(
            page_content="【公开】公司班车路线与考勤时间指南",
            metadata={
                "source": "commute.md",
                "tenant_id": "tenant_a",
                "allowed_departments": ["ALL"],
                "security_clearance_level": 1,
            },
        ),
        Document(
            page_content="【绝密】高管年终薪酬包与核心期权分配方案",
            metadata={
                "source": "executive_salary.md",
                "tenant_id": "tenant_a",
                "allowed_departments": ["财务部", "总裁办"],
                "security_clearance_level": 3,
            },
        ),
    ]

    upsert_documents(docs=docs, collection_name=collection_name, client=test_client)

    # 1. 普通客服部员工 (Clearance=1, Dept=客服部) 搜索薪酬
    cs_results = search_similar_documents(
        query="高管年终薪酬与期权",
        top_k=5,
        collection_name=collection_name,
        client=test_client,
        tenant_id="tenant_a",
        user_department="客服部",
        clearance_level=1,
    )
    # 涉密文档必须被 100% 物理阻断
    cs_contents = [d.page_content for d in cs_results]
    assert not any("高管年终薪酬" in c for c in cs_contents)

    # 2. 财务部总监 (Clearance=3, Dept=财务部) 搜索薪酬
    fin_results = search_similar_documents(
        query="高管年终薪酬与期权",
        top_k=5,
        collection_name=collection_name,
        client=test_client,
        tenant_id="tenant_a",
        user_department="财务部",
        clearance_level=3,
    )
    fin_contents = [d.page_content for d in fin_results]
    assert any("高管年终薪酬" in c for c in fin_contents)


def test_cross_tenant_isolation():
    """Test Tenant A user cannot retrieve Tenant B confidential or public documents."""
    test_client = QdrantClient(":memory:")
    collection_name = "test_multi_tenant_kb"

    docs = [
        Document(
            page_content="Tenant Alpha 核心商业机密项目代号 X",
            metadata={
                "source": "alpha_secret.md",
                "tenant_id": "tenant_alpha",
                "allowed_departments": ["ALL"],
                "security_clearance_level": 1,
            },
        ),
        Document(
            page_content="Tenant Beta 核心商业机密项目代号 Y",
            metadata={
                "source": "beta_secret.md",
                "tenant_id": "tenant_beta",
                "allowed_departments": ["ALL"],
                "security_clearance_level": 1,
            },
        ),
    ]

    upsert_documents(docs=docs, collection_name=collection_name, client=test_client)

    # Tenant Alpha 查询
    alpha_results = search_similar_documents(
        query="项目代号",
        top_k=5,
        collection_name=collection_name,
        client=test_client,
        tenant_id="tenant_alpha",
        clearance_level=1,
    )
    assert len(alpha_results) == 1
    assert "Tenant Alpha" in alpha_results[0].page_content
    assert "Tenant Beta" not in alpha_results[0].page_content


